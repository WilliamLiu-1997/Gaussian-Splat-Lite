export function plyMetadata(header) {
  const comments = [];
  let model;
  for (const line of header.split(/\r?\n/)) {
    const match = /^\s*comment(?:[ \t](.*))?$/.exec(line);
    if (!match) continue;
    const comment = match[1] ?? "";
    const lower = comment.trim().toLowerCase();
    if (lower.startsWith("splatrendermode: ")) {
      const value = lower.slice("splatrendermode: ".length).trim();
      if (value === "2dgs") model = "2dgs";
      else if (value === "mip") model = "antialiased";
      else if (value === "default") model = undefined;
    } else if (lower.startsWith("postshot.anti_aliasing=")) {
      const value = lower.slice("postshot.anti_aliasing=".length).trim();
      if (value === "1") model = "antialiased";
      else if (value === "0") model = undefined;
    } else if (
      !/^generated by (splat-transform|gaussian-splat-lite)\b/.test(lower)
    ) {
      comments.push(comment);
    }
  }
  if (model === "2dgs") throw new Error("2DGS PLY input is not supported");
  return { comments, model };
}
